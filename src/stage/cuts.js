/**
 * 컷신 — 그림 몇 장으로 시간을 만든다.
 *
 * 영상을 흉내내지 않는다. 만화가 칸 사이에서 시간을 만드는 것처럼, 그림
 * 두세 장을 겹쳐 넘기면서 그 사이에 이야기를 넣는다 (ui/reel.js 가 그린다).
 *
 * ── 액자(interlude)와 무엇이 다른가 ──
 * 액자는 "지나온 뱃길을 박물관처럼 돌아보는" 장치다. 테두리가 있고, 낡고,
 * 이미 끝난 일이다. 컷신은 **지금 눈앞에서 벌어지는 일**이다. 테두리가 없고
 * 화면을 꽉 채우고 불티가 날린다.
 *
 * 그래서 쓰는 자리가 다르다 —
 *   판과 판 사이의 뱃길        → 액자
 *   무언가가 지금 일어나는 순간 → 컷신
 *
 * hold 는 그 장이 머무는 시간(ms)이다. 1.6~2.2초가 "넘어간다" 는 느낌의
 * 하한이다. 1초보다 짧으면 읽기 전에 넘어가서 슬라이드쇼가 되고,
 * 3초보다 길면 정지 화면으로 돌아간다.
 *
 * ── 그림을 고르는 규칙 두 개 ──
 *
 * 1. **옆 액자와 같은 그림을 쓰지 않는다.**
 *    액자는 `lude-<판id>.webp` 와 `-b` 를 쓰고, 그 판을 깬 직후에 뜬다
 *    (stages.js 의 interludeFor). 컷신이 바로 앞뒤 액자와 같은 장을 쓰면
 *    1분 안에 같은 그림을 두 번 보게 되고, 그러면 그림이 없어 보인다.
 *    멀리 떨어진 판의 장은 가져다 써도 된다 — 다시 볼 때는 기억이 된다.
 *
 * 2. **글에 그림을 맞추지 않고, 그림에 글을 맞춘다.**
 *    전에는 반대로 했다. 동굴 컷신 첫 장의 글이 "동굴에는 양 떼와 치즈가
 *    있었다" 인데 그림은 폭풍우 치는 바다(lude-ismaros)였다. 없는 그림을
 *    글로 부르면 어긋난 게 그대로 화면에 남는다. 있는 그림으로 할 수 있는
 *    이야기를 한다.
 *
 * ── 대역으로 쓴 것 (솔직하게) ──
 * · 동굴 두 번째 장에 `boss/antiphates` 를 쓴다. 폴리페모스가 바위로 문을
 *   막는 그림이 없다. 안티파테스는 바위를 머리 위로 든 거인이라, 실루엣과
 *   덩치가 그 순간과 같다 — 다른 거인의 초상이라는 건 사실이다.
 * · 저승 첫 장에 `lude-ithaca`(붉은 빛이 도는 무너진 홀)를 쓴다. 저승 내부
 *   그림이 없다. 해가 들지 않는 실내라는 점만 같다.
 * · 해협 두 번째 장의 절벽은 `lude-aiaia-b` 다. 스킬라가 붙은 절벽 그림이
 *   따로 없다.
 * 아직 필요한 그림은 HANDOFF.md 에 프롬프트까지 적어 뒀다.
 */

